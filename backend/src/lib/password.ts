// =============================================================================
// 密码哈希工具（基于 bcryptjs）
// -----------------------------------------------------------------------------
// 【前端转全栈知识点】
// 为什么不能存明文密码：
//   - 数据库被拖库（脱裤），所有用户密码泄露
//   - 内部人员能直接看到密码
//   - 用户多个网站用同一密码，一处泄露全沦陷
//
// 为什么不直接 MD5/SHA256：
//   - MD5/SHA256 设计目的是"快"，密码学哈希目的是"慢"
//   - 攻击者用 GPU 每秒能算几亿次 MD5，密码秒破
//   - bcrypt 故意设计成"慢"，每次哈希约 100ms，攻击者破解成本极高
//
// bcrypt 哈希特点：
//   - 同一密码每次哈希结果不同（含随机盐 salt）
//   - 验证时用 bcrypt.compare(明文, 哈希) 自动对比
//   - 哈希结果自带算法版本和 cost（如 $2a$10$xxx）
//
// cost（计算成本）参数：
//   - 数字越大越安全，但越慢
//   - 10 是常用值（约 100ms）
//   - 每 +1，时间翻倍
//   - 服务器 CPU 升级后可调高
// =============================================================================

import bcrypt from 'bcryptjs'

// bcrypt cost（计算成本）
const SALT_ROUNDS = 10

// -----------------------------------------------------------------------------
// 密码哈希（注册/重置密码时用）
// 入：明文密码（如 '123456'）
// 出：哈希字符串（如 '$2a$10$N9qo8uLOickgx2ZMRZoMy...'）
// -----------------------------------------------------------------------------
export async function hashPassword(plain: string): Promise<string> {
  // bcryptjs 是纯 JS 实现，比 native bcrypt 慢但跨平台稳定
  return bcrypt.hash(plain, SALT_ROUNDS)
}

// -----------------------------------------------------------------------------
// 密码验证（登录时用）
// 入：明文密码（用户输入）+ 数据库里的哈希
// 出：true=密码正确，false=密码错误
// -----------------------------------------------------------------------------
export async function verifyPassword(plain: string, hash: string): Promise<boolean> {
  return bcrypt.compare(plain, hash)
}

// -----------------------------------------------------------------------------
// 密码强度校验（注册时用）
// 返回错误信息，通过则返回 null
// -----------------------------------------------------------------------------
export function validatePasswordStrength(password: string): string | null {
  if (password.length < 6) {
    return '密码至少 6 位'
  }
  if (password.length > 64) {
    return '密码不能超过 64 位'
  }
  // 一期不强制复杂度（用户体验优先）
  // 二期可加：必须含字母+数字
  return null
}
